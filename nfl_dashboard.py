def _directional_metrics(df, pred_col, actual_col, market_col):
    """MAE / bias on graded games, and directional win rate vs. the book (pushes and
    on-the-line predictions excluded) — the same counts the confusion matrix shows."""
    valid = df.dropna(subset=[pred_col, actual_col])
    if valid.empty: return np.nan, np.nan, np.nan
    mae = float(np.mean(np.abs(valid[pred_col] - valid[actual_col])))
    bias = float(np.mean(valid[pred_col] - valid[actual_col]))
    res = directional_confusion(df, pred_col, actual_col, market_col)
    win_rate = (res["cm"][0, 0] + res["cm"][1, 1]) / res["n"] * 100 if res["n"] else np.nan
    return mae, bias, win_rate

