def moneyball_confusion_figures(bt: pd.DataFrame, ci_pct: float):
    """Money Ball 2x3: rule's call (bet high / no bet / bet low) vs. actual side of the line."""
    figs = []
    for side_col, res_col, (hi, lo), (call_hi, call_lo), title in [
        ("total_side", "total_result", ("over", "under"), ("OVER", "UNDER"), "Totals"),
        ("spread_side", "spread_result", ("home_cover", "away_cover"), ("Bet home", "Bet away"), "Spreads"),
    ]:
        d = bt[bt[side_col].isin(["HIGH", "NO_BET", "LOW"]) & bt[res_col].isin([hi, lo])]
        cm = np.array([[np.sum((d[side_col] == s) & (d[res_col] == r)) for s in ["HIGH", "NO_BET", "LOW"]]
                       for r in [hi, lo]], dtype=int)
        y_labels = ["Over", "Under"] if title == "Totals" else ["Home covered", "Away covered"]
        figs.append(confusion_heatmap(cm, [call_hi, "NO BET", call_lo], y_labels,
                                      f"{title} — {ci_pct:.0f}% CrI rule vs. result", x_title="Money Ball call"))
    return figs

