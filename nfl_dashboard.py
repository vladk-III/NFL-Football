def directional_confusion(df: pd.DataFrame, pred_col: str, actual_col: str, line_col: str) -> dict:
    """2x2 counts of predicted side vs. actual side of the book line.
    Rows = actual (above line, below line); cols = predicted (above line, below line).
    For totals "above" = OVER; for spreads (home-margin scale) "above" = home covers.
    Pushes (actual == line) and no-calls (prediction == line) are excluded and counted separately,
    which matches the "Win %" column in the accuracy tables."""
    if pred_col not in df.columns or actual_col not in df.columns or line_col not in df.columns:
        return {"cm": np.zeros((2, 2), dtype=int), "n": 0, "pushes": 0, "no_call": 0}
    v = df.dropna(subset=[pred_col, actual_col, line_col])
    pushes = int((v[actual_col] == v[line_col]).sum())
    v = v[v[actual_col] != v[line_col]]
    no_call = int((v[pred_col] == v[line_col]).sum())
    v = v[v[pred_col] != v[line_col]]
    pred_hi = (v[pred_col] > v[line_col]).to_numpy()
    act_hi = (v[actual_col] > v[line_col]).to_numpy()
    cm = np.array([[np.sum(act_hi & pred_hi), np.sum(act_hi & ~pred_hi)],
                   [np.sum(~act_hi & pred_hi), np.sum(~act_hi & ~pred_hi)]], dtype=int)
    return {"cm": cm, "n": int(cm.sum()), "pushes": pushes, "no_call": no_call}

