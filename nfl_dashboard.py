def _pct(num, den):
    return f"{num / den * 100:.1f}%" if den else "—"

def confusion_summary(res: dict, hi_label: str, lo_label: str):
    """One-line read-out under a 2x2: hit rate, per-call precision, and call bias vs. reality."""
    cm, n = res["cm"], res["n"]
    hits = cm[0, 0] + cm[1, 1]
    pred_hi, act_hi = cm[:, 0].sum(), cm[0, :].sum()
    parts = [
        f"Hit rate {_pct(hits, n)} of {n}",
        f"{hi_label} calls hit {_pct(cm[0, 0], pred_hi)}",
        f"{lo_label} calls hit {_pct(cm[1, 1], cm[:, 1].sum())}",
        f"Model calls {hi_label} {_pct(pred_hi, n)} vs. actual {_pct(act_hi, n)}",
    ]
    excl = []
    if res.get("pushes"): excl.append(f"{res['pushes']} push{'es' if res['pushes'] != 1 else ''}")
    if res.get("no_call"): excl.append(f"{res['no_call']} on-the-line")
    if excl: parts.append("excluded: " + ", ".join(excl))
    return html.P(" · ".join(parts), style={"fontSize": "12.5px", "color": theme['text_main'], "margin": "4px 0 0 0"})

