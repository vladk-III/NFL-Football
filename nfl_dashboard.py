def format_spread_val(val, home_team, away_team):
    """Formats numeric home margin into standard sportsbook notation showing the favored team."""
    if pd.isna(val) or val is None:
        return "—"
    try:
        v = float(val)
    except (ValueError, TypeError):
        return "—"

    if abs(v) < 0.05:
        return "EVEN"
    elif v > 0:
        return f"{home_team} -{abs(v):.1f}"
    else:
        return f"{away_team} -{abs(v):.1f}"

