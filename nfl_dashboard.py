_CSV_CACHE: dict[str, tuple[float, pd.DataFrame]] = {}

def _load_csv(filename: str, max_age: float = CSV_CACHE_TTL_SEC) -> pd.DataFrame:
    """Loads a CSV from ./data, ., or GitHub raw. Results are cached in-process: local files
    by mtime, remote files for `max_age` seconds (pass max_age=0 to force a fresh download)."""
    local_path = Path(DATA_SUBDIR) / filename
    if not local_path.exists():
        local_path = Path(".") / filename
    if local_path.exists():
        key, stamp = f"local:{local_path.resolve()}", local_path.stat().st_mtime
        hit = _CSV_CACHE.get(key)
        if hit is None or hit[0] != stamp:
            hit = (stamp, pd.read_csv(local_path))
            _CSV_CACHE[key] = hit
        return hit[1].copy()

    url = f"https://raw.githubusercontent.com/{GITHUB_OWNER}/{GITHUB_REPO}/{GITHUB_BRANCH}/{DATA_SUBDIR}/{filename}"
    hit = _CSV_CACHE.get(url)
    if hit is not None and max_age > 0 and time.time() - hit[0] < max_age:
        return hit[1].copy()
    try:
        r = requests.get(url, timeout=15)
        if r.status_code == 200:
            df = pd.read_csv(io.StringIO(r.text))
            _CSV_CACHE[url] = (time.time(), df)
            return df.copy()
    except requests.RequestException:
        pass
    return hit[1].copy() if hit is not None else pd.DataFrame()   # stale copy beats nothing

