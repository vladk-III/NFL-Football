def completed_mask(games: pd.DataFrame) -> pd.Series:
    """Boolean mask of completed games, tolerant of bool or "True"/"False" string columns."""
    c = games["completed"]
    if c.dtype == bool:
        return c
    return c.astype(str).str.strip().str.lower() == "true"

def _norm_gid(s: pd.Series) -> pd.Series:
    return s.astype(str).str.strip().str.lower()

def completed_scores(games: pd.DataFrame) -> pd.DataFrame:
    """game_id (normalized) + final scores for completed games, one row per game."""
    if games is None or games.empty:
        return pd.DataFrame(columns=["game_id", "home_points", "away_points"])
    g = games.loc[completed_mask(games), ["game_id", "home_points", "away_points"]].copy()
    g["game_id"] = _norm_gid(g["game_id"])
    return g.dropna(subset=["home_points", "away_points"]).drop_duplicates("game_id", keep="last")

