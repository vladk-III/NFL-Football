def run_bps_pipeline(set_progress, n_particles=BPS_DEFAULT_PARTICLES,
                     delta=BPS_DEFAULT_DELTA, beta=BPS_DEFAULT_BETA):
    """
    Bayesian Predictive Synthesis via a Rao-Blackwellized particle filter (McAlinn et al. 2018).
    Filters the latent weightor theta_t = (intercept, w_1, w_2) forward through graded history,
    separately for totals (A, B) and spreads (C, B), and saves the particle system.
    """
    n_particles = _clean_int(n_particles, BPS_DEFAULT_PARTICLES, 50, 20000)
    delta = _clean_float(delta, BPS_DEFAULT_DELTA, 0.5, 1.0)
    beta = _clean_float(beta, BPS_DEFAULT_BETA, 0.5, 1.0)

    set_progress("Loading historical predictions and outcomes for BPS...")
    if not PREDICTIONS_HISTORY_PATH.exists():
        raise RuntimeError("No predictions_history.csv found. Run predictions for at least one week to build history before optimizing.")

    hist = pd.read_csv(PREDICTIONS_HISTORY_PATH)
    games = _load_csv("games.csv", max_age=0)

    if games.empty:
        raise RuntimeError("games.csv is empty. Cannot optimize against actual outcomes.")

    h = hist.copy()
    h["game_id"] = _norm_gid(h["game_id"])
    merged = h.merge(completed_scores(games), on="game_id", how="inner")
    if merged.empty:
        raise RuntimeError(f"None of the {len(h)} logged predictions match a completed game in games.csv yet, "
                           "so there is nothing to grade BPS against. Predictions are graded once their games finish "
                           "and games.csv shows final scores.")

    merged["actual_total"] = merged["home_points"] + merged["away_points"]
    merged["actual_margin"] = merged["home_points"] - merged["away_points"]

    set_progress(f"Found {len(h)} logged predictions, {len(merged)} with final scores. "
                 f"Running Rao-Blackwellized particle filter on Totals (p={n_particles}, δ={delta:g}, β={beta:g})...")
    tot = fit_bps_market(
        merged, ["modelA_total_mean", "modelB_total_mean"],
        ["modelA_total_std", "modelB_total_std"], "actual_total", n_particles, delta, beta, seed=BPS_SEED + 1)

    set_progress(f"Running Rao-Blackwellized particle filter on Spreads (p={n_particles}, δ={delta:g}, β={beta:g})...")
    spr = fit_bps_market(
        merged, ["modelC_spread_mean", "modelB_spread_mean"],
        ["modelC_spread_std", "modelB_spread_std"], "actual_margin", n_particles, delta, beta, seed=BPS_SEED + 2)

    with open(BPS_BUNDLE_PATH, "wb") as f:
        pickle.dump({"totals": tot, "spreads": spr, "n_particles": n_particles, "delta": delta, "beta": beta}, f)

    tt, ts = tot["theta_mean"], spr["theta_mean"]
    set_progress(
        f"BPS complete (p={n_particles}, δ={delta:g}, β={beta:g}). Totals θ: int={tt[0]:.2f}, A={tt[1]:.2f}, B={tt[2]:.2f} "
        f"σ={tot['vol_sd']:.1f} (n={tot['n_obs']}, ESS={tot['ess']:.0f}) | Spreads θ: int={ts[0]:.2f}, C={ts[1]:.2f}, B={ts[2]:.2f} "
        f"σ={spr['vol_sd']:.1f} (n={spr['n_obs']}, ESS={spr['ess']:.0f})")
    return {"ok": True, "totals_theta": tt, "spreads_theta": ts}


def run_predictions_pipeline(set_progress, n_samples=BPS_DEFAULT_SAMPLES,
                             n_particles=BPS_DEFAULT_PARTICLES,
                             delta=BPS_DEFAULT_DELTA, beta=BPS_DEFAULT_BETA):
    n_samples = _clean_int(n_samples, BPS_DEFAULT_SAMPLES, 200, 100000)
    n_particles = _clean_int(n_particles, BPS_DEFAULT_PARTICLES, 50, 20000)
    delta = _clean_float(delta, BPS_DEFAULT_DELTA, 0.5, 1.0)
    beta = _clean_float(beta, BPS_DEFAULT_BETA, 0.5, 1.0)

    set_progress("Loading prediction features and model states...")
    pred_df = pd.read_csv(STATE_DIR / "pred_df.csv").reset_index(drop=True)

    if pred_df.empty:
        raise RuntimeError("No upcoming games in pred_df.csv. Re-run step 1 after the schedule updates.")
    current_week = pred_df["week"].min()
    pred_df = pred_df[pred_df["week"] == current_week].reset_index(drop=True)
    set_progress(f"Filtered predictions to current upcoming week (Week {current_week}).")

    with open(STATE_DIR / "scaler.pkl", "rb") as f: scaler = Standardizer.from_state(pickle.load(f))

    set_progress("Fetching latest market odds from GitHub...")
    odds_df = _load_csv("odds_snapshots.csv", max_age=0)
    if odds_df.empty:
        odds_df = _load_csv("odds_snapshot.csv", max_age=0)

    trace_a = az.from_netcdf(str(STATE_DIR / "trace_a.nc"))
    trace_b = az.from_netcdf(str(STATE_DIR / "trace_b.nc"))
    trace_c = az.from_netcdf(str(STATE_DIR / "trace_c.nc"))

    dummy = pred_df.copy()
    dummy["total_points"], dummy["margin"] = 50.0, 0.0

    set_progress("Generating posterior predictions for Totals (Model A)...")
    with build_model_a_beta(dummy, scaler):
        a_preds = pm.sample_posterior_predictive(trace_a, var_names=["total_obs"], progressbar=False).posterior_predictive
        a_samps = a_preds["total_obs"].to_numpy().reshape(-1, len(pred_df)) * 100.0

    set_progress("Generating posterior predictions for Poisson Baseline (Model B)...")
    with build_model_b_poisson(dummy, scaler):
        b_preds = pm.sample_posterior_predictive(trace_b, var_names=["h_obs", "a_obs"], progressbar=False).posterior_predictive
        b_h_samps = b_preds["h_obs"].to_numpy().reshape(-1, len(pred_df))
        b_a_samps = b_preds["a_obs"].to_numpy().reshape(-1, len(pred_df))
        b_total_samps = b_h_samps + b_a_samps
        b_spread_samps = b_h_samps - b_a_samps

    set_progress("Generating posterior predictions for Spreads (Model C)...")
    with build_model_c_beta(dummy, scaler):
        c_preds = pm.sample_posterior_predictive(trace_c, var_names=["margin_obs"], progressbar=False).posterior_predictive
        c_samps = c_preds["margin_obs"].to_numpy().reshape(-1, len(pred_df)) * 100.0 - 50.0

    set_progress("Merging current market lines...")
    market_index = build_market_index(odds_df)
    market_df = pd.DataFrame([lookup_market_lines(market_index, h, a)
                              for h, a in zip(pred_df["home_team"], pred_df["away_team"])])

    set_progress("Loading BPS particle filters...")
    flt_tot, flt_spr = load_bps_filters(set_progress, n_particles, delta, beta)

    set_progress(f"Synthesizing BPS predictive draws ({n_samples:,} per game per market)...")
    out = pred_df[["game_id", "season", "week", "start_date", "home_team", "away_team"]].copy()

    out["modelA_total_mean"] = a_samps.mean(axis=0)
    out["modelB_total_mean"] = b_total_samps.mean(axis=0)
    out["modelB_spread_mean"] = b_spread_samps.mean(axis=0)
    out["modelC_spread_mean"] = c_samps.mean(axis=0)
    # Agent predictive std devs: needed so the particle filter can sample each agent's density
    out["modelA_total_std"] = a_samps.std(axis=0)
    out["modelB_total_std"] = b_total_samps.std(axis=0)
    out["modelB_spread_std"] = b_spread_samps.std(axis=0)
    out["modelC_spread_std"] = c_samps.std(axis=0)
    out["market_ou_price"] = -110

    out = pd.concat([out.reset_index(drop=True), market_df.reset_index(drop=True)], axis=1)
    out["market_implied_home_margin"] = -out["market_spread_median"]

    tot_line = out["market_total_median"].to_numpy(float)
    spr_line = out["market_implied_home_margin"].to_numpy(float)
    recs = []
    for i in range(len(out)):
        pt = flt_tot.predict([out.at[i, "modelA_total_mean"], out.at[i, "modelB_total_mean"]],
                             [out.at[i, "modelA_total_std"], out.at[i, "modelB_total_std"]], n_samples)
        ps = flt_spr.predict([out.at[i, "modelC_spread_mean"], out.at[i, "modelB_spread_mean"]],
                             [out.at[i, "modelC_spread_std"], out.at[i, "modelB_spread_std"]], n_samples)
        pool_t, pool_s = pt["draws"], ps["draws"]
        st, ss = summarize_pool(pool_t, tot_line[i]), summarize_pool(pool_s, spr_line[i])
        recs.append({
            "combined_total_mean": st["mean"], "combined_total_median": st["median"], "combined_total_std": st["std"],
            "combined_spread_mean": ss["mean"], "combined_spread_median": ss["median"], "combined_spread_std": ss["std"],
            "edge_total_mean": st["edge"], "edge_total_median": st["median"] - tot_line[i],
            "edge_spread_mean": ss["edge"], "edge_spread_median": ss["median"] - spr_line[i],
            "edge_total_z": st["z"], "edge_spread_z": ss["z"],
            "model_prob_total": st["prob"] * 100, "model_prob_spread": ss["prob"] * 100,
            # P(total > book line) from the BPS predictive — the probability the Brier score grades.
            # (Previously this was Model A's P(total > 45.5) regardless of the actual line.)
            "model_prob_over": float((pool_t > tot_line[i]).mean()) if np.isfinite(tot_line[i]) else np.nan,
            "total_draws_json": json.dumps(np.round(pool_t[:MAX_STORED_DRAWS], 1).tolist()),
            "spread_draws_json": json.dumps(np.round(pool_s[:MAX_STORED_DRAWS], 1).tolist()),
        })
    out = pd.concat([out, pd.DataFrame(recs)], axis=1)
    out["total_tier"] = out["edge_total_z"].apply(edge_tier)
    out["spread_tier"] = out["edge_spread_z"].apply(edge_tier)

    set_progress("Saving prediction history...")
    history_cols = ["game_id", "season", "week", "start_date", "home_team", "away_team",
                    "modelA_total_mean", "modelB_total_mean", "modelC_spread_mean", "modelB_spread_mean",
                    "modelA_total_std", "modelB_total_std", "modelC_spread_std", "modelB_spread_std",
                    "combined_total_mean", "combined_total_median", "combined_total_std",
                    "combined_spread_mean", "combined_spread_median", "combined_spread_std",
                    "market_total_median", "market_spread_median", "market_implied_home_margin",
                    "edge_total_mean", "edge_total_median", "edge_spread_mean", "edge_spread_median",
                    "edge_total_z", "edge_spread_z", "total_tier", "spread_tier",
                    "model_prob_over", "market_ou_price",
                    "total_draws_json", "spread_draws_json"]

    this_week_hist = out[history_cols].copy()
    this_week_hist["predicted_at"] = pd.Timestamp.now(tz="UTC").strftime("%Y-%m-%dT%H:%M:%SZ")

    if PREDICTIONS_HISTORY_PATH.exists():
        try:
            existing = pd.read_csv(PREDICTIONS_HISTORY_PATH)
            combined_hist = pd.concat([existing, this_week_hist], ignore_index=True)
            combined_hist = combined_hist.sort_values("predicted_at").drop_duplicates(subset=["game_id"], keep="last")
        except Exception:
            combined_hist = this_week_hist
    else:
        combined_hist = this_week_hist
    combined_hist.to_csv(PREDICTIONS_HISTORY_PATH, index=False)

    set_progress("Predictions complete!")
    return {"ok": True, "data": out.to_json(orient="records")}

