def _first_float(row: pd.Series, possible_cols) -> float:
    for col_name in possible_cols:
        if col_name in row.index:
            try:
                v = float(row[col_name])
                if not pd.isna(v): return v
            except (ValueError, TypeError):
                pass
    return np.nan

def build_market_index(odds: pd.DataFrame) -> dict:
    """Pre-indexes an odds snapshot table once: {(HOME, AWAY): market-line dict}.
    Per matchup it prefers DraftKings rows when present and keeps the latest snapshot.
    Replaces the old per-game scan of the whole odds table (O(games x odds rows))."""
    if odds is None or odds.empty or "home_team" not in odds.columns or "away_team" not in odds.columns:
        return {}
    o = odds.copy()
    o["_h"] = o["home_team"].map(normalize_team_name)
    o["_a"] = o["away_team"].map(normalize_team_name)

    book_col = next((c for c in ["provider", "bookmaker", "book", "title", "sportsbook"] if c in o.columns), None)
    if book_col:
        o["_dk"] = o[book_col].astype(str).str.lower().str.replace(" ", "").str.contains("draftkings").fillna(False)
        has_dk = o.groupby(["_h", "_a"])["_dk"].transform("any")
        o = o[o["_dk"] | ~has_dk]

    if "snapshot_ts" in o.columns:
        o = o.sort_values("snapshot_ts", kind="mergesort")
    latest = o.groupby(["_h", "_a"], sort=False).tail(1)

    index = {}
    for _, row in latest.iterrows():
        spread = _first_float(row, ["spread", "point_spread", "spread_line", "handicap", "line"])
        over_under = _first_float(row, ["over_under", "total", "total_line", "ou_line", "points"])
        index[(row["_h"], row["_a"])] = {
            "market_spread_mean": spread, "market_total_mean": over_under,
            "market_spread_median": spread, "market_total_median": over_under,
            "market_spread_price": _first_float(row, ["spread_price", "spread_odds", "price"]),
            "market_ou_price_consensus": _first_float(row, ["ou_price", "ou_odds", "over_price"]),
            "n_books": 1,
        }
    return index

def lookup_market_lines(index: dict, home_team: str, away_team: str) -> dict:
    t_home, t_away = normalize_team_name(home_team), normalize_team_name(away_team)
    hit = index.get((t_home, t_away))
    if hit is None:   # fuzzy fallback (substring either way), over unique matchups only
        hit = next((v for (h, a), v in index.items()
                    if (t_home in h or h in t_home) and (t_away in a or a in t_away)), None)
    return dict(hit) if hit is not None else dict(EMPTY_MARKET_LINES)

def get_consensus_market_lines(odds: pd.DataFrame, home_team: str, away_team: str) -> dict:
    """Kept for compatibility. For many games, build the index once and use lookup_market_lines."""
    return lookup_market_lines(build_market_index(odds), home_team, away_team)

# =============================================================================
# BAYESIAN PREDICTIVE SYNTHESIS — Rao-Blackwellized particle filter
# =============================================================================
# Synthesis model (McAlinn et al. 2018):   y_t = theta_t' x_t + nu_t,  nu_t ~ N(0, V_t)
#   x_t     = (1, x_1t, x_2t): intercept + one draw from each agent's forecast density
#   theta_t = theta_{t-1} + omega_t           (random walk; R_t = C_{t-1} / delta)
#   V_t     = discounted-variance random walk (h_t = beta*h_{t-1} + 1, D_t = beta*D_{t-1} + S*e^2/Q)
# Each particle i carries the Kalman posterior (m_i, C_i) of theta (Rao-Blackwellized: theta is
# marginalized analytically), its own volatility state (h_i, D_i), and a weight. Per game every
# particle draws its own x from the agents' densities N(mean, std). Weights are updated with the
# one-step predictive likelihood (Normal approximation to the T_{beta*h} predictive), and
# systematic resampling fires on ESS drop. Weights are NOT sign-constrained.
class BPSFilter:
    DIM = 3  # intercept + 2 agents

    def __init__(self, n_particles, delta=BPS_DEFAULT_DELTA, beta=BPS_DEFAULT_BETA,
                 obs_var0=BPS_FALLBACK_OBS_VAR, seed=BPS_SEED):
        self.n = int(n_particles)
        self.delta = float(delta)
        self.beta = float(beta)
        self.rng = np.random.default_rng(seed)
        self.m = np.tile(np.array([0.0, 0.5, 0.5]), (self.n, 1))
        C0 = np.diag([BPS_PRIOR_INTERCEPT_SD**2, BPS_PRIOR_WEIGHT_SD**2, BPS_PRIOR_WEIGHT_SD**2])
        self.C = np.tile(C0, (self.n, 1, 1))
        self.h = np.full(self.n, float(BPS_PRIOR_DOF))
        self.D = np.full(self.n, float(BPS_PRIOR_DOF) * float(obs_var0))
        self.w = np.full(self.n, 1.0 / self.n)

    # -- agent sampling ------------------------------------------------------
    def _draw_x(self, mu, sd, n):
        z = self.rng.standard_normal((n, 2))
        X = np.ones((n, self.DIM))
        X[:, 1:] = np.asarray(mu, float) + np.asarray(sd, float) * z
        return X

    @property
    def ess(self):
        return 1.0 / np.sum(self.w ** 2)

    def theta_mean(self):
        return self.w @ self.m

    def vol_mean(self):
        """Posterior-mean residual std (sqrt of weighted S = D/h)."""
        return float(np.sqrt(self.w @ (self.D / self.h)))

    # -- one filtering step with an observed outcome ---------------------------
    def update(self, mu, sd, y):
        X = self._draw_x(mu, sd, self.n)                       # genuine MC draws, one per particle
        R = self.C / self.delta                                 # state prior covariance (discount delta)
        f = np.einsum("ni,ni->n", X, self.m)                    # predictive mean
        RX = np.einsum("nij,nj->ni", R, X)
        S = self.D / self.h                                     # current volatility estimate
        Q = np.einsum("ni,ni->n", X, RX) + S                    # predictive variance
        e = y - f
        loglik = -0.5 * (np.log(2 * np.pi * Q) + e ** 2 / Q)

        logw = np.log(self.w + 1e-300) + loglik
        logw -= logw.max()
        w = np.exp(logw)
        self.w = w / w.sum()

        # Kalman update of theta for each particle
        K = RX / Q[:, None]
        self.m = self.m + K * e[:, None]
        C = R - K[:, :, None] * RX[:, None, :]
        self.C = 0.5 * (C + C.transpose(0, 2, 1))

        # Discounted volatility update (discount beta)
        self.h = self.beta * self.h + 1.0
        self.D = self.beta * self.D + S * e ** 2 / Q

        if self.ess < BPS_ESS_FRAC * self.n:                    # systematic resampling
            pos = (self.rng.random() + np.arange(self.n)) / self.n
            cs = np.cumsum(self.w); cs[-1] = 1.0
            idx = np.searchsorted(cs, pos)
            self.m, self.C, self.h, self.D = self.m[idx], self.C[idx], self.h[idx], self.D[idx]
            self.w = np.full(self.n, 1.0 / self.n)

    # -- posterior predictive for a new game ---------------------------------------
    def predict(self, mu, sd, n_draws):
        """Draw n_draws samples from the BPS predictive mixture. Each draw picks a particle by
        weight, draws fresh agent forecasts, and adds synthesis noise. Mean/variance follow the
        law of total variance: Var = E[Q] + Var[f]."""
        n_draws = int(n_draws)
        w = self.w / self.w.sum()
        idx = self.rng.choice(self.n, size=n_draws, p=w)
        X = self._draw_x(mu, sd, n_draws)
        R = self.C[idx] / self.delta
        f = np.einsum("di,di->d", X, self.m[idx])
        Q = np.einsum("di,dij,dj->d", X, R, X) + self.D[idx] / self.h[idx]
        draws = f + np.sqrt(Q) * self.rng.standard_normal(n_draws)
        return {"draws": draws, "mean": float(f.mean()), "var": float(Q.mean() + f.var())}

    def get_state(self):
        return {"n": self.n, "delta": self.delta, "beta": self.beta,
                "m": self.m, "C": self.C, "h": self.h, "D": self.D, "w": self.w}

    @classmethod
    def from_state(cls, state, seed=BPS_SEED):
        delta = state.get("delta", state.get("discount", BPS_DEFAULT_DELTA))   # old bundles used "discount"
        obj = cls(state["n"], delta, state.get("beta", 1.0), state.get("obs_var", BPS_FALLBACK_OBS_VAR), seed)
        obj.m, obj.C, obj.w = state["m"], state["C"], state["w"]
        if "h" in state and "D" in state:
            obj.h, obj.D = state["h"], state["D"]
        return obj


def fit_bps_market(df, mu_cols, sd_cols, actual_col, n_particles,
                   delta=BPS_DEFAULT_DELTA, beta=BPS_DEFAULT_BETA, seed=BPS_SEED):
    """Runs the particle filter forward through graded history for one market (totals or spreads)."""
    d = df.dropna(subset=mu_cols + [actual_col]).copy()
    if len(d) < 3:
        raise RuntimeError(f"Only {len(d)} graded game(s) with usable agent forecasts; BPS needs at least 3 "
                           "(run weekly predictions and let games finish to build graded history).")
    d["start_date"] = pd.to_datetime(d["start_date"], errors="coerce")
    d = d.sort_values(["start_date", "game_id"])

    y = d[actual_col].to_numpy(float)
    MU = d[mu_cols].to_numpy(float)

    # Agents logged before std columns existed fall back to their empirical RMSE.
    fallback_sd = np.sqrt(np.mean((MU - y[:, None]) ** 2, axis=0))
    SD = np.empty_like(MU)
    for k, c in enumerate(sd_cols):
        s_ = d[c].to_numpy(float) if c in d.columns else np.full(len(d), np.nan)
        SD[:, k] = np.where(np.isfinite(s_) & (s_ > 0), s_, fallback_sd[k])

    resid_var = float(np.var(y - MU.mean(axis=1)))
    obs_var0 = max(BPS_OBS_VAR_FRAC * resid_var, 1e-3)

    flt = BPSFilter(n_particles, delta, beta, obs_var0, seed)
    for t in range(len(y)):
        flt.update(MU[t], SD[t], y[t])

    return {"state": flt.get_state(), "n_obs": int(len(y)), "theta_mean": flt.theta_mean().tolist(),
            "vol_sd": flt.vol_mean(), "ess": float(flt.ess), "fallback_sd": fallback_sd.tolist(),
            "delta": float(delta), "beta": float(beta)}


def load_bps_filters(set_progress, n_particles=BPS_DEFAULT_PARTICLES,
                     delta=BPS_DEFAULT_DELTA, beta=BPS_DEFAULT_BETA):
    """Returns (totals_filter, spreads_filter). A fitted bundle uses the p / delta / beta it was
    trained with (so predictions stay consistent with the fit); the p / delta / beta passed here are
    only used for the prior-only fallback when no bundle exists yet."""
    if BPS_BUNDLE_PATH.exists():
        try:
            with open(BPS_BUNDLE_PATH, "rb") as f:
                bundle = pickle.load(f)
            ft = BPSFilter.from_state(bundle["totals"]["state"], seed=BPS_SEED + 1)
            fs = BPSFilter.from_state(bundle["spreads"]["state"], seed=BPS_SEED + 2)
            tt, ts = bundle["totals"]["theta_mean"], bundle["spreads"]["theta_mean"]
            set_progress(f"Loaded BPS filters (p={ft.n}, δ={ft.delta:g}, β={ft.beta:g}). "
                         f"Totals θ=[{tt[0]:.2f}, A={tt[1]:.2f}, B={tt[2]:.2f}] "
                         f"Spreads θ=[{ts[0]:.2f}, C={ts[1]:.2f}, B={ts[2]:.2f}]")
            return ft, fs
        except Exception as e:
            LOG.warning("Could not load BPS bundle (%s); using prior filters.", e)
    set_progress(f"No fitted BPS bundle found — using prior (50/50) synthesis with p={n_particles}, "
                 f"δ={delta:g}, β={beta:g}. Run step 2 once games are graded.")
    return (BPSFilter(n_particles, delta, beta, BPS_FALLBACK_OBS_VAR, seed=BPS_SEED + 1),
            BPSFilter(n_particles, delta, beta, BPS_FALLBACK_OBS_VAR, seed=BPS_SEED + 2))


def _clean_float(value, default, lo, hi):
    try:
        v = float(value)
    except (TypeError, ValueError):
        return default
    if not np.isfinite(v):
        return default
    return max(lo, min(hi, v))

def _clean_int(value, default, lo, hi):
    try:
        v = int(round(float(value)))
    except (TypeError, ValueError):
        return default
    return max(lo, min(hi, v))

