PRIOR_STAT_MAP = {"off_epa_per_play": "off_epa_per_play", "def_epa_per_play": "def_epa_per_play",
                  "td_count": "td_rate", "fg_made": "fg_rate"}

def build_feature_table(games, team_stats, weather, only_completed: bool) -> pd.DataFrame:
    """Vectorized: each team's expanding mean of its PRIOR games (shift(1)), joined onto every
    game for the home and away side, plus weather. Same output as the old row-by-row loop."""
    comp = completed_mask(games)
    subset = games[comp].copy() if only_completed else games[~comp].copy()
    if subset.empty: return pd.DataFrame()

    df = subset[["game_id", "season", "week", "start_date", "home_team", "away_team"]].copy()
    for c in ["home_points", "away_points"]:
        df[c] = subset[c] if c in subset.columns else np.nan

    stat_cols = [c for c in PRIOR_STAT_MAP if not team_stats.empty and c in team_stats.columns]
    if stat_cols:
        m = team_stats.merge(games[["game_id", "start_date"]], on="game_id", how="inner")
        m = m.sort_values(["team", "start_date"], kind="mergesort").reset_index(drop=True)
        prior = m[["team", "game_id"]].copy()
        for c in stat_cols:
            x = pd.to_numeric(m[c], errors="coerce")
            filled, cnt = x.fillna(0.0), x.notna().astype(float)
            csum = filled.groupby(m["team"]).cumsum() - filled      # sum over earlier games only
            ccnt = cnt.groupby(m["team"]).cumsum() - cnt
            prior[c] = csum / ccnt.where(ccnt > 0)
        prior = prior.drop_duplicates(["team", "game_id"], keep="last")
        for side in ("home", "away"):
            ren = {c: f"{side}_{PRIOR_STAT_MAP[c]}" for c in stat_cols}
            df = df.merge(prior.rename(columns={"team": f"{side}_team", **ren}),
                          on=[f"{side}_team", "game_id"], how="left")
    for side in ("home", "away"):
        for c in PRIOR_STAT_MAP.values():
            col = f"{side}_{c}"
            df[col] = df[col].fillna(0.0) if col in df.columns else 0.0

    if not weather.empty:
        wx = weather[["game_id", "temperature", "wind_speed"]].drop_duplicates("game_id", keep="last")
        df = df.merge(wx.rename(columns={"temperature": "wx_temp", "wind_speed": "wx_wind"}), on="game_id", how="left")
    else:
        df["wx_temp"], df["wx_wind"] = np.nan, np.nan
    df["wx_temp"] = df["wx_temp"].fillna(70.0)
    df["wx_wind"] = df["wx_wind"].fillna(0.0)

    df["epa_net_diff"] = (df["home_off_epa_per_play"] - df["home_def_epa_per_play"]) - (df["away_off_epa_per_play"] - df["away_def_epa_per_play"])

    if only_completed:
        df["total_points"] = df["home_points"] + df["away_points"]
        df["margin"] = df["home_points"] - df["away_points"]
    return df.reset_index(drop=True)

class Standardizer:
    def __init__(self, cols): self.cols, self.mean_, self.std_ = cols, None, None
    def fit(self, df):
        self.mean_, self.std_ = df[self.cols].mean(), df[self.cols].std().replace(0, 1.0)
        return self
    def transform(self, df): return ((df[self.cols] - self.mean_) / self.std_).fillna(0.0).to_numpy()
    def get_state(self): return {"cols": self.cols, "mean_": self.mean_, "std_": self.std_}
    @classmethod
    def from_state(cls, state):
        obj = cls(state["cols"]); obj.mean_, obj.std_ = state["mean_"], state["std_"]
        return obj

COVARIATE_COLS = ["epa_net_diff", "wx_temp", "wx_wind"]

def odds_to_prob(american_odds):
    if pd.isna(american_odds): return np.nan
    return -american_odds / (-american_odds + 100) if american_odds < 0 else 100 / (american_odds + 100)

def devig_probability(implied_prob, standard_vig=1.0476):
    return implied_prob / standard_vig if pd.notna(implied_prob) else np.nan

