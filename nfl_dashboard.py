def build_model_a_beta(train_df, scaler, min_tot=0.0, max_tot=100.0):
    X = scaler.transform(train_df)
    y = np.clip((train_df["total_points"].to_numpy(dtype=np.float64) - min_tot) / (max_tot - min_tot), 1e-4, 1.0 - 1e-4)
    with pm.Model(coords={"cov": COVARIATE_COLS}) as model:
        X_data = pm.Data("X", X, dims=("game", "cov"))
        y_data = pm.Data("y_data", y, dims="game")
        mu = pm.Deterministic("mu", pm.math.sigmoid(pm.Normal("a", 0, 1) + pm.math.dot(X_data, pm.Normal("b", 0, 1, dims="cov"))))
        kappa = pm.Exponential("kappa", 0.1)
        pm.Beta("total_obs", alpha=mu * kappa, beta=(1.0 - mu) * kappa, observed=y_data, dims="game")
    return model

def build_model_b_poisson(df, scaler, coords=None):
    if coords is None:
        coords = {"game": np.arange(len(df)), "cov": COVARIATE_COLS}

    X = scaler.transform(df)
    h_pts = df.get("home_points", pd.Series(np.zeros(len(df)))).fillna(0).to_numpy(dtype=np.int64)
    a_pts = df.get("away_points", pd.Series(np.zeros(len(df)))).fillna(0).to_numpy(dtype=np.int64)

    with pm.Model(coords=coords) as model:
        X_data = pm.Data("X", X, dims=("game", "cov"))
        h_obs_data = pm.Data("h_obs_data", h_pts, dims="game")
        a_obs_data = pm.Data("a_obs_data", a_pts, dims="game")

        # Log-link function for Poisson regression using covariates
        mu_h = pm.math.exp(pm.Normal("alpha_h", 3.0, 1.0) + pm.math.dot(X_data, pm.Normal("beta_h", 0, 0.5, dims="cov")))
        mu_a = pm.math.exp(pm.Normal("alpha_a", 3.0, 1.0) + pm.math.dot(X_data, pm.Normal("beta_a", 0, 0.5, dims="cov")))

        pm.Poisson("h_obs", mu=mu_h, observed=h_obs_data, dims="game")
        pm.Poisson("a_obs", mu=mu_a, observed=a_obs_data, dims="game")

    return model

def build_model_c_beta(train_df, scaler, min_m=-50.0, max_m=50.0):
    X = scaler.transform(train_df)
    y = np.clip((train_df["margin"].to_numpy(dtype=np.float64) - min_m) / (max_m - min_m), 1e-4, 1.0 - 1e-4)
    with pm.Model(coords={"cov": COVARIATE_COLS}) as model:
        X_data = pm.Data("X", X, dims=("game", "cov"))
        y_data = pm.Data("y_data", y, dims="game")
        mu = pm.Deterministic("mu", pm.math.sigmoid(pm.Normal("a", 0, 1) + pm.math.dot(X_data, pm.Normal("b", 0, 1, dims="cov"))))
        kappa = pm.Exponential("kappa", 0.1)
        pm.Beta("margin_obs", alpha=mu * kappa, beta=(1.0 - mu) * kappa, observed=y_data, dims="game")
    return model

def _resolve_sampler() -> str:
    if NUTS_SAMPLER == "auto":
        return "nutpie" if importlib.util.find_spec("nutpie") is not None else "pymc"
    return NUTS_SAMPLER

def sample_model(model, seed):
    """pm.sample with the fastest available backend. nutpie runs chains on threads inside one
    process, so it's safe inside Dash's background-callback worker; the PyMC sampler stays on
    cores=1 there to avoid nested multiprocessing."""
    sampler = _resolve_sampler()
    kw = dict(model=model, draws=DRAWS, tune=TUNE, chains=CHAINS, progressbar=False, random_seed=seed)
    if sampler != "pymc":
        try:
            return pm.sample(nuts_sampler=sampler, **kw)
        except Exception as e:
            LOG.warning("%s sampler failed (%s); falling back to PyMC NUTS.", sampler, e)
    return pm.sample(cores=1, **kw)

