def summarize_pool(pool: np.ndarray, market_val: float) -> dict:
    if pool is None or len(pool) == 0:
        return {"mean": np.nan, "median": np.nan, "std": np.nan, "edge": np.nan, "prob": np.nan, "z": np.nan}
    mean, median, std = float(np.mean(pool)), float(np.median(pool)), float(np.std(pool))
    if pd.isna(market_val):
        return {"mean": mean, "median": median, "std": std, "edge": np.nan, "prob": np.nan, "z": np.nan}
    edge = mean - market_val
    prob = float((pool > market_val).mean() if edge > 0 else (pool < market_val).mean())
    z = edge / std if std > 0 else np.nan
    return {"mean": mean, "median": median, "std": std, "edge": edge, "prob": prob, "z": z}

def edge_tier(z):
    if pd.isna(z): return "No Line"
    az_ = abs(z)
    if az_ >= 1.5: return "★★★ Strong"
    if az_ >= 0.75: return "★★☆ Moderate"
    return "★☆☆ Slight"

def credible_interval_bounds(conf_level: float) -> tuple[float, float]:
    lower_pct = (100.0 - conf_level * 100.0) / 2.0
    return lower_pct, 100.0 - lower_pct

def _side_vs_interval(market_val, lower, upper):
    if pd.isna(market_val) or pd.isna(lower) or pd.isna(upper): return None
    if market_val < lower: return "HIGH"
    if market_val > upper: return "LOW"
    return "NO_BET"

def moneyball_interval_from_draws(draws, market_val, conf_level: float):
    if draws is None or len(draws) == 0:
        return np.nan, np.nan, None
    lower_pct, upper_pct = credible_interval_bounds(conf_level)
    lower, upper = np.percentile(draws, [lower_pct, upper_pct])
    return float(lower), float(upper), _side_vs_interval(market_val, lower, upper)

def load_stored_draws(row: pd.Series, prefix: str):
    raw = row.get(f"{prefix}_draws_json")
    if raw is None or (isinstance(raw, float) and pd.isna(raw)) or raw == "":
        return None
    if isinstance(raw, list):
        return np.asarray(raw, dtype=float)
    if isinstance(raw, str):
        try:
            return np.asarray(json.loads(raw), dtype=float)
        except (ValueError, TypeError, json.JSONDecodeError):
            return None
    return None

def _sorted_draws(raw):
    """Parses a stored draws payload once and returns it sorted (or None)."""
    arr = load_stored_draws(pd.Series({"x_draws_json": raw}), "x")
    if arr is None:
        return None
    arr = arr[np.isfinite(arr)]
    return np.sort(arr) if arr.size else None

def _quantile_sorted(s: np.ndarray, pct: float) -> float:
    """np.percentile(..., method='linear') on an already-sorted array, in O(1)."""
    pos = pct / 100.0 * (s.size - 1)
    lo = int(np.floor(pos)); hi = min(lo + 1, s.size - 1)
    return float(s[lo] + (s[hi] - s[lo]) * (pos - lo))

def _prob_above(s: np.ndarray, line: float) -> float:
    if s is None or pd.isna(line): return np.nan
    return 1.0 - np.searchsorted(s, line, side="right") / s.size

def moneyball_live_table(out_df: pd.DataFrame, conf_level: float, market: str) -> pd.DataFrame:
    pct = int(round(conf_level * 100))
    rows = []
    for _, r in out_df.iterrows():
        prefix = "total" if market == "total" else "spread"
        draws = load_stored_draws(r, prefix)
        mkt = r.get("market_total_median") if market == "total" else r.get("market_implied_home_margin")

        lower, upper, side = moneyball_interval_from_draws(draws, mkt, conf_level)

        if side is None: call = "No Line"
        elif side == "NO_BET": call = "NO BET"
        elif market == "total": call = "OVER" if side == "HIGH" else "UNDER"
        else: call = r["home_team"] if side == "HIGH" else r["away_team"]

        # Format lower/upper bounds for spread market to show team relative lines
        if market == "spread":
            fmt_lower = format_spread_val(lower, r["home_team"], r["away_team"])
            fmt_upper = format_spread_val(upper, r["home_team"], r["away_team"])
            fmt_mkt = format_spread_val(mkt, r["home_team"], r["away_team"])
        else:
            fmt_lower = round(lower, 1) if pd.notna(lower) else None
            fmt_upper = round(upper, 1) if pd.notna(upper) else None
            fmt_mkt = round(mkt, 1) if pd.notna(mkt) else None

        rows.append({
            "Game": f"{r['away_team']} @ {r['home_team']}", "Week": r["week"],
            f"{pct}% CrI Lower": fmt_lower,
            f"{pct}% CrI Upper": fmt_upper,
            "Book Line": fmt_mkt,
            "Call": call,
        })
    return pd.DataFrame(rows)

def _actual_total_result(actual_total, market_total):
    if pd.isna(actual_total) or pd.isna(market_total): return None
    if actual_total == market_total: return "push"
    return "over" if actual_total > market_total else "under"

def _actual_spread_result(actual_margin, market_spread):
    if pd.isna(actual_margin) or pd.isna(market_spread): return None
    net = actual_margin + market_spread
    if net == 0: return "push"
    return "home_cover" if net > 0 else "away_cover"

# ---- Graded history: parsed once, cached, reused by every backtest / sweep level ----------
_GRADED_CACHE: dict = {}

def prepare_graded_history(hist_df: pd.DataFrame, games_df: pd.DataFrame) -> pd.DataFrame | None:
    """Joins prediction history to final scores, computes actual results vs. the book, and parses
    each game's stored posterior draws ONCE (sorted). The old code re-parsed every game's JSON
    draws for each of the 13 sweep levels; this does it once and caches on the inputs' content."""
    if hist_df is None or games_df is None or hist_df.empty or games_df.empty:
        return None
    try:
        key = (int(pd.util.hash_pandas_object(hist_df, index=False).sum()),
               int(pd.util.hash_pandas_object(games_df.astype(str), index=False).sum()))
    except Exception:
        key = None
    if key is not None and key in _GRADED_CACHE:
        return _GRADED_CACHE[key]

    h = hist_df.copy()
    h["game_id"] = _norm_gid(h["game_id"])
    h = h.drop(columns=[c for c in ["home_points", "away_points", "actual_total", "actual_margin"] if c in h.columns])
    merged = h.merge(completed_scores(games_df), on="game_id", how="inner")
    if merged.empty:
        result = None
    else:
        if "market_implied_home_margin" not in merged.columns and "market_spread_median" in merged.columns:
            merged["market_implied_home_margin"] = -merged["market_spread_median"]
        for c in ["market_total_median", "market_spread_median", "market_implied_home_margin"]:
            if c not in merged.columns:
                merged[c] = np.nan
        merged["actual_total"] = merged["home_points"] + merged["away_points"]
        merged["actual_margin"] = merged["home_points"] - merged["away_points"]
        merged["total_result"] = [_actual_total_result(a, m) for a, m in zip(merged["actual_total"], merged["market_total_median"])]
        merged["spread_result"] = [_actual_spread_result(a, m) for a, m in zip(merged["actual_margin"], merged["market_spread_median"])]
        for prefix in ("total", "spread"):
            col = f"{prefix}_draws_json"
            merged[f"_{prefix}_sorted"] = (merged[col].map(_sorted_draws) if col in merged.columns
                                           else pd.Series([None] * len(merged), index=merged.index, dtype=object))
        result = merged.reset_index(drop=True)

    if key is not None:
        if len(_GRADED_CACHE) > 8: _GRADED_CACHE.clear()
        _GRADED_CACHE[key] = result
    return result

def backtest_from_prepared(prep: pd.DataFrame, conf_level: float) -> dict:
    if prep is None or prep.empty:
        return {"empty": True}
    lower_pct, upper_pct = credible_interval_bounds(conf_level)

    def _intervals(prefix, line_col):
        lo, hi, side = [], [], []
        for s, mkt in zip(prep[f"_{prefix}_sorted"], prep[line_col]):
            if s is None:
                lo.append(np.nan); hi.append(np.nan); side.append(None); continue
            l, u = _quantile_sorted(s, lower_pct), _quantile_sorted(s, upper_pct)
            lo.append(l); hi.append(u); side.append(_side_vs_interval(mkt, l, u))
        return lo, hi, side

    lo_t, hi_t, side_t = _intervals("total", "market_total_median")
    lo_s, hi_s, side_s = _intervals("spread", "market_implied_home_margin")
    bt = pd.DataFrame({
        "total_side": side_t, "total_lower": lo_t, "total_upper": hi_t,
        "total_result": prep["total_result"], "actual_total": prep["actual_total"],
        "spread_side": side_s, "spread_lower": lo_s, "spread_upper": hi_s,
        "spread_result": prep["spread_result"], "actual_margin": prep["actual_margin"],
    })

    def _grade(df, side_col, result_col, high_label, low_label):
        n_usable = df[side_col].isin(["HIGH", "LOW", "NO_BET"]).sum()
        bets = df[df[side_col].isin(["HIGH", "LOW"])].copy()
        if bets.empty:
            return {"n_games": int(n_usable), "n_bets": 0, "selectivity": 0.0, "win_rate": np.nan, "n_graded": 0}
        bets["pick"] = np.where(bets[side_col] == "HIGH", high_label, low_label)
        graded = bets[bets[result_col] != "push"]
        win_rate = (graded["pick"] == graded[result_col]).mean() * 100 if len(graded) else np.nan
        return {"n_games": int(n_usable), "n_bets": len(bets),
                "selectivity": len(bets) / n_usable * 100 if n_usable else 0.0,
                "win_rate": win_rate, "n_graded": len(graded)}

    def _coverage(df, lower_col, upper_col, actual_col):
        valid = df.dropna(subset=[lower_col, upper_col, actual_col])
        if valid.empty: return np.nan
        outside = (valid[actual_col] < valid[lower_col]) | (valid[actual_col] > valid[upper_col])
        return outside.mean() * 100

    return {
        "empty": False,
        "bt": bt,
        "totals": _grade(bt, "total_side", "total_result", "over", "under"),
        "spreads": _grade(bt, "spread_side", "spread_result", "home_cover", "away_cover"),
        "totals_outside_pct": _coverage(bt, "total_lower", "total_upper", "actual_total"),
        "spreads_outside_pct": _coverage(bt, "spread_lower", "spread_upper", "actual_margin"),
        "nominal_outside_pct": (1 - conf_level) * 100,
    }

def compute_moneyball_backtest(hist_df: pd.DataFrame, games_df: pd.DataFrame, conf_level: float) -> dict:
    return backtest_from_prepared(prepare_graded_history(hist_df, games_df), conf_level)

def moneyball_sweep(prep: pd.DataFrame, levels=None) -> pd.DataFrame:
    if levels is None:
        levels = np.arange(0.50, 0.8001, 0.025)
    rows = []
    for lvl in levels:
        res = backtest_from_prepared(prep, float(lvl))
        if res.get("empty"):
            continue
        rows.append({
            "CI Level": lvl * 100,
            "Totals Selectivity": res["totals"]["selectivity"], "Totals Win Rate": res["totals"]["win_rate"],
            "Spreads Selectivity": res["spreads"]["selectivity"], "Spreads Win Rate": res["spreads"]["win_rate"],
        })
    return pd.DataFrame(rows)

